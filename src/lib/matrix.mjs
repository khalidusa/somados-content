/** وسوم: محلية + عامة + وسم المدينة + الوسم التجاري. */
export function buildHashtags(rng, tags, { cityCode, visaCountry, kind }, shuffle) {
  const out = [
    ...shuffle(rng, tags.market).slice(0, 2),
    ...shuffle(rng, tags.core).slice(0, 4),
    ...(cityCode && tags.city[cityCode] ? tags.city[cityCode] : []),
    ...(kind === 'visa' ? shuffle(rng, tags.visa).slice(0, 2) : []),
    ...(visaCountry && tags.visaCountry[visaCountry] ? tags.visaCountry[visaCountry] : []),
    ...tags.brand
  ];
  return [...new Set(out)];
}
